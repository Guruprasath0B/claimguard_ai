def random_digits(length: int) -> str:
    return "".join(random.choices(string.digits, k=length))


def generate_aadhaar() -> str:
    return random_digits(12)


def generate_pan() -> str:
    letters = "".join(random.choices(string.ascii_uppercase, k=5))
    numbers = random_digits(4)
    final_letter = random.choice(string.ascii_uppercase)
    return f"{letters}{numbers}{final_letter}"


def generate_abha() -> str:
    return f"{random_digits(8)}-{random_digits(4)}-{random_digits(4)}"


def generate_phone() -> str:
    return "9" + random_digits(9)


