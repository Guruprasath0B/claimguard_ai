# ============================================================
# POLICY DOCUMENTS
# ============================================================

def generate_policy_documents(
    clauses: list[dict[str, Any]],
) -> list[dict[str, Any]]:

    documents = []

    grouped: dict[str, list[dict[str, Any]]] = {}

    for clause in clauses:
        grouped.setdefault(
            clause["policy_type"],
            [],
        ).append(clause)

    for policy_type, policy_clauses in grouped.items():

        documents.append(
            {
                "document_id": (
                    f"DOC-{policy_type}-2026"
                ),
                "document_type": "POLICY_GUIDELINE",
                "policy_type": policy_type,
                "effective_date": "2026-01-01",
                "version": "2026.1",
                "source": "ClaimGuard Synthetic Policy Repository",
                "clauses": policy_clauses,
            }
        )

    return documents


