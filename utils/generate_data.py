def random_date_between(
    start: date,
    end: date,
) -> date:

    delta = (end - start).days

    return start + timedelta(
        days=random.randint(0, max(delta, 1))
    )


def generate_claims(
    patients: list[dict[str, Any]],
    hospitals: list[dict[str, Any]],
) -> list[dict[str, Any]]:

    claims = []

    for index in range(1, CLAIM_COUNT + 1):

        patient = random.choice(patients)
        hospital = random.choice(hospitals)
        diagnosis = random.choice(DIAGNOSES)

        procedure = random.choice(
            diagnosis["procedures"]
        )

        claim_type = random.choice(
            CLAIM_TYPES
        )

        admission_date = date(2026, 1, 1) + timedelta(
            days=random.randint(0, 220)
        )

        length_of_stay = random.randint(
            1,
            10
        )

        discharge_date = (
            admission_date
            + timedelta(days=length_of_stay)
        )

        room_limit = (
            patient["sum_insured_inr"]
            * patient["room_rent_limit_percent"]
            / 100
        )

        room_multiplier = random.choices(
            [0.8, 1.0, 1.25, 1.6, 2.0],
            weights=[20, 35, 25, 15, 5],
        )[0]

        room_charge = int(
            room_limit * room_multiplier
        )

        procedure_cost = random.randint(
            30000,
            180000
        )

        diagnostics = random.randint(
            5000,
            30000
        )

        pharmacy = random.randint(
            5000,
            40000
        )

        consumables = random.randint(
            2000,
            18000
        )

        miscellaneous = random.randint(
            1000,
            10000
        )

        room_total = room_charge * length_of_stay

        requested_amount = (
            room_total
            + procedure_cost
            + diagnostics
            + pharmacy
            + consumables
            + miscellaneous
        )

        anomaly_type = random.choices(
            [
                "NONE",
                "ROOM_RENT_EXCESS",
                "NON_PAYABLE_ITEMS",
                "TIMELINE_MISMATCH",
                "UNBUNDLING",
                "DUPLICATE_CHARGE",
                "HIGH_VALUE_ANOMALY",
            ],
            weights=[
                50,
                15,
                10,
                8,
                7,
                5,
                5,
            ],
        )[0]

        fraud_flags = []

        if anomaly_type == "ROOM_RENT_EXCESS":
            fraud_flags.append(
                "ROOM_RENT_LIMIT_EXCEEDED"
            )

        elif anomaly_type == "NON_PAYABLE_ITEMS":
            fraud_flags.append(
                "NON_PAYABLE_ITEMS_DETECTED"
            )

        elif anomaly_type == "TIMELINE_MISMATCH":
            fraud_flags.append(
                "TIMELINE_MISMATCH"
            )

        elif anomaly_type == "UNBUNDLING":
            fraud_flags.append(
                "POSSIBLE_UNBUNDLING"
            )

        elif anomaly_type == "DUPLICATE_CHARGE":
            fraud_flags.append(
                "POSSIBLE_DUPLICATE_CHARGE"
            )

        elif anomaly_type == "HIGH_VALUE_ANOMALY":
            fraud_flags.append(
                "HIGH_VALUE_ANOMALY"
            )

        if fraud_flags:
            fraud_risk = random.choice(
                ["MEDIUM", "HIGH"]
            )
        else:
            fraud_risk = random.choices(
                ["LOW", "MEDIUM"],
                weights=[90, 10],
            )[0]

        claims.append(
            {
                "claim_id": f"CLM-2026-IN-{index:06d}",
                "patient_id": patient["patient_id"],
                "policy_id": patient["policy_id"],
                "hospital_id": hospital["hospital_id"],
                "claim_type": claim_type,
                "submission_channel": random.choice(
                    ["PORTAL", "API", "TPA_PORTAL", "CLI_SIMULATION"]
                ),
                "diagnosis": diagnosis["name"],
                "icd10_code": diagnosis["icd10"],
                "procedure": procedure,
                "admission_date": admission_date.isoformat(),
                "discharge_date": discharge_date.isoformat(),
                "length_of_stay_days": length_of_stay,
                "room_category": random.choice(
                    [room[0] for room in ROOM_CATEGORIES]
                ),
                "room_charge_per_day_inr": room_charge,
                "room_eligible_per_day_inr": round(
                    room_limit,
                    2
                ),
                "procedure_cost_inr": procedure_cost,
                "diagnostics_inr": diagnostics,
                "pharmacy_inr": pharmacy,
                "consumables_inr": consumables,
                "miscellaneous_inr": miscellaneous,
                "requested_amount_inr": requested_amount,
                "policy_sum_insured_inr": patient[
                    "sum_insured_inr"
                ],
                "policy_balance_before_claim_inr": max(
                    patient["sum_insured_inr"]
                    - patient["cumulative_claimed_inr"],
                    0,
                ),
                "ped_waiting_period_months": patient[
                    "ped_waiting_period_months"
                ],
                "declared_peds": patient[
                    "declared_peds"
                ],
                "anomaly_type": anomaly_type,
                "fraud_flags": fraud_flags,
                "fraud_risk_expected": fraud_risk,
                "expected_claim_status": random.choice(
                    CLAIM_STATUSES
                ),
            }
        )

    return claims


