# CLAIM LINE ITEMS
# ============================================================

def generate_claim_line_items(
    claims: list[dict[str, Any]],
) -> list[dict[str, Any]]:

    items = []

    item_id = 1

    for claim in claims:

        line_definitions = [
            (
                "ROOM_RENT",
                claim["room_charge_per_day_inr"]
                * claim["length_of_stay_days"],
            ),
            (
                "PROCEDURE",
                claim["procedure_cost_inr"],
            ),
            (
                "DIAGNOSTICS",
                claim["diagnostics_inr"],
            ),
            (
                "PHARMACY",
                claim["pharmacy_inr"],
            ),
            (
                "CONSUMABLES",
                claim["consumables_inr"],
            ),
            (
                "MISCELLANEOUS",
                claim["miscellaneous_inr"],
            ),
        ]

        for category, amount in line_definitions:

            payable = True
            deduction_reason = None

            if (
                category == "CONSUMABLES"
                and random.random() < 0.65
            ):
                payable = False
                deduction_reason = random.choice(
                    NON_PAYABLE_ITEMS
                )

            items.append(
                {
                    "line_item_id": f"LINE-{item_id:08d}",
                    "claim_id": claim["claim_id"],
                    "category": category,
                    "description": (
                        deduction_reason
                        if deduction_reason
                        else category.replace("_", " ").title()
                    ),
                    "amount_inr": amount,
                    "payable": payable,
                    "deduction_reason": deduction_reason,
                }
            )

            item_id += 1

    return items


